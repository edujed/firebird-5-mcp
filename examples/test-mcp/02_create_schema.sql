-- =============================================================================
-- test-mcp — Schema DDL
-- Test database for the firebird-5-mcp MCP server.
--
-- This script is idempotent: it can be run multiple times.
-- Existing objects are dropped before being recreated.
--
-- Usage:
--   1. Create the database:  firebird_create_database  (via MCP)
--   2. Run this script:      firebird_run_script  (via MCP)
--   3. Run seed.sql:         firebird_run_script  (via MCP)
-- =============================================================================

-- ---------------------------------------------------------------------------
-- DROP (order respects dependencies: dependents before referenced)
-- Firebird does not support IF EXISTS for DROP, so we use EXECUTE BLOCK
-- to check existence before dropping.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- DOMAINS
-- ---------------------------------------------------------------------------

CREATE DOMAIN D_BOOLEAN AS BOOLEAN DEFAULT FALSE NOT NULL;
CREATE DOMAIN D_INTEGER AS INTEGER;
CREATE DOMAIN D_TIMESTAMP AS TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL;
CREATE DOMAIN D_VARCHAR_100 AS VARCHAR(100);
CREATE DOMAIN D_VARCHAR_200 AS VARCHAR(200);

-- ---------------------------------------------------------------------------
-- SEQUENCES
-- ---------------------------------------------------------------------------

CREATE SEQUENCE GEN_USER_ID START WITH 1;
CREATE SEQUENCE GEN_APPROVAL_ID START WITH 1;

-- ---------------------------------------------------------------------------
-- TABLES
-- ---------------------------------------------------------------------------

CREATE TABLE PROFILE (
    ID          INTEGER       NOT NULL,
    NAME        VARCHAR(100)  NOT NULL,
    DESCRIPTION VARCHAR(500),
    ACTIVE      BOOLEAN       DEFAULT TRUE NOT NULL,
    CREATED_AT  D_TIMESTAMP   NOT NULL,
    CONSTRAINT PK_PROFILE PRIMARY KEY (ID)
);

CREATE TABLE PERMISSION (
    ID          INTEGER       NOT NULL,
    CODE        VARCHAR(50)   NOT NULL,
    NAME        VARCHAR(100)  NOT NULL,
    MODULE      VARCHAR(50)   NOT NULL,
    ACTIVE      BOOLEAN       DEFAULT TRUE NOT NULL,
    CONSTRAINT PK_PERMISSION PRIMARY KEY (ID),
    CONSTRAINT UK_PERMISSION_CODE UNIQUE (CODE)
);

CREATE TABLE SCREEN (
    ID          INTEGER       NOT NULL,
    NAME        VARCHAR(100)  NOT NULL,
    MODULE      VARCHAR(50)   NOT NULL,
    PATH        VARCHAR(200)  NOT NULL,
    ACTIVE      BOOLEAN       DEFAULT TRUE,
    CONSTRAINT PK_SCREEN PRIMARY KEY (ID)
);

CREATE TABLE BRANCH (
    ID          INTEGER       NOT NULL,
    NAME        VARCHAR(100)  NOT NULL,
    CODE        VARCHAR(10)   NOT NULL,
    ACTIVE      D_BOOLEAN     NOT NULL,
    CREATED_AT  D_TIMESTAMP   NOT NULL,
    UPDATED_AT  D_TIMESTAMP   NOT NULL,
    CONSTRAINT PK_BRANCH PRIMARY KEY (ID),
    CONSTRAINT UK_BRANCH_CODE UNIQUE (CODE)
);

CREATE TABLE DEPARTMENT (
    ID              INTEGER       NOT NULL,
    BRANCH_ID       INTEGER       NOT NULL,
    PARENT_ID       INTEGER,
    NAME            VARCHAR(100)  NOT NULL,
    CODE            VARCHAR(20)   NOT NULL,
    TYPE            VARCHAR(20)   DEFAULT 'PHYSICAL' NOT NULL,
    ACTIVE          BOOLEAN       DEFAULT TRUE,
    CREATED_AT      D_TIMESTAMP   NOT NULL,
    UPDATED_AT      D_TIMESTAMP   NOT NULL,
    CONSTRAINT PK_DEPARTMENT PRIMARY KEY (ID),
    CONSTRAINT UK_DEPARTMENT_CODE UNIQUE (CODE),
    CONSTRAINT FK_DEPT_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCH (ID),
    CONSTRAINT FK_DEPT_PARENT FOREIGN KEY (PARENT_ID) REFERENCES DEPARTMENT (ID)
);

CREATE TABLE USERS (
    ID              INTEGER       NOT NULL,
    DEPARTMENT_ID   INTEGER       NOT NULL,
    NAME            VARCHAR(100)  NOT NULL,
    EMAIL           VARCHAR(200)  NOT NULL,
    PASSWORD_HASH   VARCHAR(500)  NOT NULL,
    ACTIVE          BOOLEAN       DEFAULT TRUE NOT NULL,
    SALARY          NUMERIC(14,2) DEFAULT 0 NOT NULL,
    HIRED_AT        DATE          NOT NULL,
    CREATED_AT      D_TIMESTAMP   NOT NULL,
    UPDATED_AT      D_TIMESTAMP   NOT NULL,
    CONSTRAINT PK_USER PRIMARY KEY (ID),
    CONSTRAINT UK_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_USER_DEPT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENT (ID)
);

CREATE TABLE USER_DEPARTMENT (
    ID              INTEGER   NOT NULL,
    USER_ID         INTEGER   NOT NULL,
    DEPARTMENT_ID   INTEGER   NOT NULL,
    PRIMARY_FLAG    BOOLEAN,
    START_DATE      DATE      NOT NULL,
    END_DATE        DATE,
    ACTIVE          BOOLEAN   DEFAULT TRUE,
    CONSTRAINT PK_USER_DEPT PRIMARY KEY (ID),
    CONSTRAINT UK_USER_DEPT UNIQUE (USER_ID, DEPARTMENT_ID, START_DATE),
    CONSTRAINT FK_UD_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_UD_DEPT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENT (ID)
);

CREATE TABLE USER_PROFILE (
    ID          INTEGER   NOT NULL,
    USER_ID     INTEGER   NOT NULL,
    PROFILE_ID  INTEGER   NOT NULL,
    CONSTRAINT PK_USER_PROFILE PRIMARY KEY (ID),
    CONSTRAINT UK_USER_PROFILE UNIQUE (USER_ID, PROFILE_ID),
    CONSTRAINT FK_UP_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_UP_PROFILE FOREIGN KEY (PROFILE_ID) REFERENCES PROFILE (ID)
);

CREATE TABLE PROFILE_PERMISSION (
    ID              INTEGER NOT NULL,
    PROFILE_ID      INTEGER NOT NULL,
    PERMISSION_ID   INTEGER NOT NULL,
    CONSTRAINT PK_PROFILE_PERM PRIMARY KEY (ID),
    CONSTRAINT UK_PROFILE_PERM UNIQUE (PROFILE_ID, PERMISSION_ID),
    CONSTRAINT FK_PP_PROFILE FOREIGN KEY (PROFILE_ID) REFERENCES PROFILE (ID),
    CONSTRAINT FK_PP_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSION (ID)
);

CREATE TABLE PROFILE_SCREEN (
    ID          INTEGER   NOT NULL,
    PROFILE_ID  INTEGER   NOT NULL,
    SCREEN_ID   INTEGER   NOT NULL,
    CONSTRAINT PK_PROFILE_SCREEN PRIMARY KEY (ID),
    CONSTRAINT UK_PROFILE_SCREEN UNIQUE (PROFILE_ID, SCREEN_ID),
    CONSTRAINT FK_PS_PROFILE FOREIGN KEY (PROFILE_ID) REFERENCES PROFILE (ID),
    CONSTRAINT FK_PS_SCREEN FOREIGN KEY (SCREEN_ID) REFERENCES SCREEN (ID)
);

CREATE TABLE APPROVAL (
    ID              INTEGER       NOT NULL,
    REQUESTER_ID    INTEGER       NOT NULL,
    APPROVER_ID     INTEGER       NOT NULL,
    STATUS          VARCHAR(20)   DEFAULT 'PENDING' NOT NULL,
    REASON          VARCHAR(500),
    APPROVED_AT     TIMESTAMP,
    CREATED_AT      D_TIMESTAMP   NOT NULL,
    CONSTRAINT PK_APPROVAL PRIMARY KEY (ID),
    CONSTRAINT FK_APPROVAL_REQUESTER FOREIGN KEY (REQUESTER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_APPROVAL_APPROVER FOREIGN KEY (APPROVER_ID) REFERENCES USERS (ID)
);

CREATE TABLE ACTION_LOG (
    ID          INTEGER       NOT NULL,
    USER_ID     INTEGER       NOT NULL,
    ACTION      VARCHAR(50)   NOT NULL,
    ENTITY      VARCHAR(50)   NOT NULL,
    ENTITY_ID   INTEGER,
    DETAILS     VARCHAR(1000),
    CREATED_AT  D_TIMESTAMP   NOT NULL,
    CONSTRAINT PK_ACTION_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_LOG_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

-- ---------------------------------------------------------------------------
-- VIEWS
-- ---------------------------------------------------------------------------

CREATE VIEW VW_USER_DEPARTMENT AS
SELECT
    U.ID          AS USER_ID,
    U.NAME        AS USER_NAME,
    U.EMAIL       AS USER_EMAIL,
    D.ID          AS DEPARTMENT_ID,
    D.NAME        AS DEPARTMENT_NAME,
    D.CODE        AS DEPARTMENT_CODE,
    B.ID          AS BRANCH_ID,
    B.NAME        AS BRANCH_NAME,
    B.CODE        AS BRANCH_CODE,
    UD.PRIMARY_FLAG,
    UD.START_DATE,
    UD.END_DATE,
    UD.ACTIVE     AS ASSIGNMENT_ACTIVE
FROM USERS U
JOIN USER_DEPARTMENT UD ON UD.USER_ID = U.ID
JOIN DEPARTMENT D ON D.ID = UD.DEPARTMENT_ID
JOIN BRANCH B ON B.ID = D.BRANCH_ID;

CREATE VIEW VW_APPROVAL_SUMMARY AS
SELECT
    A.ID              AS APPROVAL_ID,
    A.STATUS          AS STATUS,
    A.REASON          AS REASON,
    A.CREATED_AT      AS CREATED_AT,
    A.APPROVED_AT     AS APPROVED_AT,
    R.ID              AS REQUESTER_ID,
    R.NAME            AS REQUESTER_NAME,
    R.EMAIL           AS REQUESTER_EMAIL,
    P.ID              AS APPROVER_ID,
    P.NAME            AS APPROVER_NAME,
    P.EMAIL           AS APPROVER_EMAIL
FROM APPROVAL A
JOIN USERS R ON R.ID = A.REQUESTER_ID
JOIN USERS P ON P.ID = A.APPROVER_ID;
